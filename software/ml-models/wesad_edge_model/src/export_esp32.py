# ============================================================================= B. header
def _lit(v: float) -> str:
    return f"(auralis_real){float(v)!r}"


def header_text(json_path: Path = JSON_PATH) -> str:
    raw = json_path.read_bytes()
    c = json.loads(raw.decode("utf-8"))
    sha = hashlib.sha256(raw).hexdigest()
    order = c["feature_order"]
    assert order == ["hr_mean", "eda_slope_rel", "scr_count_rel"], order
    nf = len(order)
    sm = c["smoothing"]
    assert 1 <= sm["m"] <= sm["n"] <= 8, "smoother uses one byte of history"
    cal = c["calibration"]
    arr = lambda xs: "{ " + ", ".join(_lit(x) for x in xs) + " }"
    enum = ",\n    ".join(f"AURALIS_F_{n.upper()} = {i}" for i, n in enumerate(order))
    return f"""/*
 * GENERATED by src/export_esp32.py from models/stress_lr_D_w30.json - DO NOT EDIT BY HAND.
 * Source JSON sha256: {sha}
 *
 * Stress detection model D (logistic regression; WESAD lab stressor = TSST, NOT panic or anxiety).
 * Score: x_i <- median_i if x_i is NaN; z = bias + sum_i w_i * x_i; window alert if z >= logit threshold (OP1).
 * Default output: OP1 + {sm['m']}-of-{sm['n']} smoothing over consecutive {c['step_s']} s windows.
 * The score is NOT a calibrated probability: never show it to a wearer as "probability of stress".
 * Validated only on WESAD Empatica E4 wrist data; NOT validated on the prototype (fingertip MAX30102, finger GSR in mV).
 *
 * Inputs (feature order, units; definitions in models/feature_spec.json, version {c['feature_spec_version']}):
 *   [0] hr_mean        bpm      BVP {c['input_rates_hz']['BVP']} Hz, causal 0.7-3.5 Hz band-pass, peaks, mean of 60/IBI
 *   [1] eda_slope_rel  1/s      LS slope of low-passed EDA / sigma_lp_cal
 *   [2] scr_count_rel  count    phasic EDA peaks with prominence >= sigma_ph_cal, >= 1 s apart
 * Both EDA features need the per-wearer calibration statistics (sigma_lp_cal, sigma_ph_cal) from a
 * {cal['duration_s']} s seated rest at first use (models/calibration_procedure.md).
 */
#ifndef AURALIS_STRESS_LR_D_W30_H
#define AURALIS_STRESS_LR_D_W30_H

#ifndef AURALIS_REAL
#define AURALIS_REAL float          /* ESP32: single-precision FPU; double is emulated in software */
#endif
typedef AURALIS_REAL auralis_real;

#define AURALIS_MODEL_CONFIG        "{c['config']}"
#define AURALIS_FEATURE_SPEC_VERSION "{c['feature_spec_version']}"
#define AURALIS_N_FEATURES          {nf}
#define AURALIS_FEATURE_ORDER       "{','.join(order)}"
enum {{
    {enum}
}};

#define AURALIS_WINDOW_S            {c['window_s']}
#define AURALIS_STEP_S              {c['step_s']}
#define AURALIS_FS_BVP_HZ           {c['input_rates_hz']['BVP']}
#define AURALIS_FS_EDA_HZ           {c['input_rates_hz']['EDA']}
#define AURALIS_SMOOTH_M            {sm['m']}
#define AURALIS_SMOOTH_N            {sm['n']}
#define AURALIS_CAL_DURATION_S      {cal['duration_s']}
#define AURALIS_CAL_STORED          "{','.join(cal['stored_on_device'])}"

static const auralis_real AURALIS_WEIGHTS[AURALIS_N_FEATURES] = {arr(c['weights_folded'])};
static const auralis_real AURALIS_BIAS = {_lit(c['bias_folded'])};
static const auralis_real AURALIS_IMPUTER_MEDIANS[AURALIS_N_FEATURES] = {arr(c['imputer_medians'])};
static const auralis_real AURALIS_THRESHOLD_OP1 = {_lit(c['threshold_op1'])};        /* on p = 1/(1+exp(-z)) */
static const auralis_real AURALIS_LOGIT_THRESHOLD_OP1 = {_lit(c['logit_threshold_op1'])};  /* on z (no exp) */

/* z = bias + sum w_i x_i, NaN inputs replaced by the training medians (x != x is the portable NaN test). */
static inline auralis_real auralis_logit(const auralis_real x[AURALIS_N_FEATURES]) {{
    auralis_real z = AURALIS_BIAS;
    for (int i = 0; i < AURALIS_N_FEATURES; i++) {{
        auralis_real xi = (x[i] != x[i]) ? AURALIS_IMPUTER_MEDIANS[i] : x[i];
        z = z + AURALIS_WEIGHTS[i] * xi;
    }}
    return z;
}}

/* 1 = stress alert for this window (OP1), 0 = no alert. */
static inline int auralis_window_alert(const auralis_real x[AURALIS_N_FEATURES]) {{
    return auralis_logit(x) >= AURALIS_LOGIT_THRESHOLD_OP1;
}}

#ifdef AURALIS_WITH_SCORE
#include <math.h>
/* Host checks only: the uncalibrated score in [0, 1]. Not needed on the device. */
static inline auralis_real auralis_score(const auralis_real x[AURALIS_N_FEATURES]) {{
    return (auralis_real)(1.0 / (1.0 + exp(-(double)auralis_logit(x))));
}}
#endif

/* Causal m-of-n smoother over consecutive windows; windows not yet seen count as negative.
   A withheld window (failed quality check) must be pushed as 0. */
typedef struct {{ unsigned char hist; }} auralis_smoother;
static inline void auralis_smoother_reset(auralis_smoother *s) {{ s->hist = 0; }}
static inline int auralis_smooth_push(auralis_smoother *s, int window_alert) {{
    int k = 0;
    s->hist = (unsigned char)(((s->hist << 1) | (window_alert ? 1u : 0u)) & ((1u << AURALIS_SMOOTH_N) - 1u));
    for (int i = 0; i < AURALIS_SMOOTH_N; i++) k += (s->hist >> i) & 1u;
    return k >= AURALIS_SMOOTH_M;
}}

#endif /* AURALIS_STRESS_LR_D_W30_H */
"""


def write_header() -> Path:
    HEADER_PATH.write_text(header_text(), encoding="utf-8", newline="\n")
    return HEADER_PATH


def parse_header_constants(text: str) -> dict:
    """Read the numeric constants back from the header text (used by the tests)."""
    out = {}
    for name in ("WEIGHTS", "IMPUTER_MEDIANS"):
        m = re.search(rf"AURALIS_{name}\[AURALIS_N_FEATURES\] = \{{(.*?)\}};", text)
        out[name] = [float(v) for v in re.findall(r"\(auralis_real\)([-+0-9.eE]+)", m.group(1))]
    for name in ("BIAS", "THRESHOLD_OP1", "LOGIT_THRESHOLD_OP1"):
        out[name] = float(re.search(rf"AURALIS_{name} = \(auralis_real\)([-+0-9.eE]+);", text).group(1))
    for name in ("WINDOW_S", "STEP_S", "SMOOTH_M", "SMOOTH_N", "FS_BVP_HZ", "FS_EDA_HZ", "CAL_DURATION_S"):
        out[name] = int(re.search(rf"#define AURALIS_{name}\s+(\d+)", text).group(1))
    out["FEATURE_ORDER"] = re.search(r'#define AURALIS_FEATURE_ORDER\s+"([^"]+)"', text).group(1).split(",")
    return out


# ============================================================================= compilers
def find_host_compiler():
    """('gcc'|'clang'|'msvc', path) or None.  MSVC is found through vswhere / the standard VS 2022 location."""
    for cc in ("gcc", "clang"):
        p = shutil.which(cc)
        if p:
            return cc, p
    if shutil.which("cl"):
        return "msvc", None
    vswhere = Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / \
        "Microsoft Visual Studio" / "Installer" / "vswhere.exe"
    roots = []
    if vswhere.exists():
        r = subprocess.run([str(vswhere), "-latest", "-products", "*", "-property", "installationPath"],
                           capture_output=True, text=True)
        roots += [l.strip() for l in r.stdout.splitlines() if l.strip()]
    roots += glob.glob(r"C:\Program Files\Microsoft Visual Studio\*\*")
    for r in roots:
        v = Path(r) / "VC" / "Auxiliary" / "Build" / "vcvars64.bat"
        if v.exists():
            return "msvc", str(v)
    return None


def find_xtensa():
    pats = [os.path.join(os.environ.get("LOCALAPPDATA", ""), "Arduino15", "packages", "esp32", "tools", "esp-x32",
                         "*", "bin", "xtensa-esp32-elf-gcc.exe"),
            os.path.expanduser("~/.espressif/tools/xtensa-esp*-elf/*/xtensa-esp*-elf/bin/xtensa-esp32-elf-gcc*")]
    for p in pats:
        hits = sorted(glob.glob(p))
        if hits:
            return hits[-1]
    return shutil.which("xtensa-esp32-elf-gcc")


def build_harness(real: str) -> Path:
    """Compile the harness with AURALIS_REAL=real. Returns the executable path. Raises if no compiler."""
    cc = find_host_compiler()
    if cc is None:
        raise RuntimeError("no host C compiler (gcc / clang / MSVC cl) found")
    BUILD.mkdir(parents=True, exist_ok=True)
    exe = BUILD / f"model_harness_{real}.exe"
    defs = [f"AURALIS_REAL={real}", "AURALIS_WITH_SCORE"]
    if cc[0] == "msvc":
        dflags = " ".join(f"/D{d}" for d in defs)
        cmd = (f'cl /nologo /O2 /fp:precise /W4 /WX /wd4996 {dflags} /I"{MODELS}" "{HARNESS}" '
               f'/Fe:"{exe}" /Fo:"{BUILD / ("h_" + real + ".obj")}"')
        bat = BUILD / f"build_{real}.bat"
        pre = f'call "{cc[1]}" >nul\r\n' if cc[1] else ""
        bat.write_text("@echo off\r\n" + pre + cmd + "\r\n", encoding="ascii")
        r = subprocess.run(["cmd", "/c", str(bat)], capture_output=True, text=True)
    else:
        r = subprocess.run([cc[1], "-O2", "-std=c99", "-Wall", "-Wextra", "-Werror", *[f"-D{d}" for d in defs],
                            f"-I{MODELS}", str(HARNESS), "-o", str(exe), "-lm"], capture_output=True, text=True)
    if r.returncode != 0 or not exe.exists():
        raise RuntimeError(f"compile failed ({cc[0]}):\n{r.stdout}\n{r.stderr}")
    return exe


def c_test(verbose: bool = True) -> dict:
    """Run the C harness (float and double) on the 300 real rows of roundtrip_windows.csv; compare with Python."""
    from src.runner import smooth
    cc = find_host_compiler()
    out = {"host_compiler": cc[0] if cc else None}
    if cc is None:
        out["status"] = "NOT RUN: no host C compiler found; the C code has not been compiled or run"
        return out
    write_header_if_stale()
    rt = pd.read_csv(MODELS / "roundtrip_windows.csv")
    real = rt[rt.synthetic_nan == 0].reset_index(drop=True)
    assert len(real) == 300
    BUILD.mkdir(parents=True, exist_ok=True)
    coef = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    inp = {}
    for name, df in (("real300", real), ("synthetic_nan40", rt[rt.synthetic_nan == 1].reset_index(drop=True))):
        p = BUILD / f"in_{name}.csv"
        # same text as models/roundtrip_windows.csv (rows copied verbatim, no re-formatting of numbers)
        lines = (MODELS / "roundtrip_windows.csv").read_text(encoding="utf-8").splitlines()
        hdr, body = lines[0], lines[1:]
        flag = 1 if name.startswith("synthetic") else 0
        keep = [l for l in body if int(l.split(",")[5]) == flag]
        p.write_text("\n".join([hdr] + keep) + "\n", encoding="utf-8")
        inp[name] = (p, df)
    for real_t in ("float", "double"):
        exe = build_harness(real_t)
        for name, (p, df) in inp.items():
            o = BUILD / f"out_{real_t}_{name}.csv"
            r = subprocess.run([str(exe), "score", str(p), str(o)], capture_output=True, text=True)
            assert r.returncode == 0, r.stderr
            c = pd.read_csv(o)
            assert (c.subject.values == df.subject.values).all() and (c.t_start_s.values == df.t_start_s.values).all()
            p_ref = df.p_ref.values
            a_ref = df.alert_op1_ref.values.astype(int)
            out[f"{real_t}_{name}"] = {
                "n_rows": int(len(c)), "sizeof_real": int(c.sizeof_real.iloc[0]),
                "max_abs_p_diff_vs_p_ref": float(np.max(np.abs(c.p.values - p_ref))),
                "alert_differs_vs_alert_op1_ref": int((c.alert_logit.values != a_ref).sum()),
                "min_abs_logit_margin": float(np.min(np.abs(c.z.values - coef["logit_threshold_op1"])))}
        # smoother vs runner.smooth on one consecutive grid of decisions (SYNTHETIC 0/1 sequence + real alerts)
        rng = np.random.default_rng(0)
        seq = np.r_[rng.integers(0, 2, 400), real.alert_op1_ref.values.astype(int)]
        sp = BUILD / "smooth_in.txt"
        sp.write_text("\n".join(map(str, seq)) + "\n")
        so = BUILD / f"smooth_out_{real_t}.txt"
        r = subprocess.run([str(exe), "smooth", str(sp), str(so)], capture_output=True, text=True)
        assert r.returncode == 0, r.stderr
        cs = np.loadtxt(so, dtype=int)
        ref = smooth(seq, np.zeros(len(seq)), np.arange(len(seq)) * 5.0, coef["smoothing"]["m"], coef["smoothing"]["n"])
        out[f"{real_t}_smoother"] = {"n": int(len(seq)), "differs_vs_runner_smooth": int((cs != ref).sum())}
        r = subprocess.run([str(exe), "bench", str(inp["real300"][0]), "200000"], capture_output=True, text=True)
        out[f"{real_t}_bench_pc"] = r.stdout.strip()
    out["status"] = "RUN on this PC (host compiler); NOT run on an ESP32"
    out.update(xtensa_size())
    if verbose:
        print(json.dumps(out, indent=2))
    return out


def xtensa_size() -> dict:
    gcc = find_xtensa()
    if not gcc:
        return {"xtensa": "NOT RUN: xtensa-esp32-elf-gcc not found"}
    BUILD.mkdir(parents=True, exist_ok=True)
    unit = BUILD / "esp32_size_unit.c"
    unit.write_text('#include "stress_lr_D_w30.h"\n'
                    "int auralis_probe(const float x[3], auralis_smoother *s) {\n"
                    "    return auralis_smooth_push(s, auralis_window_alert(x));\n}\n", encoding="ascii")
    obj = BUILD / "esp32_size_unit.o"
    r = subprocess.run([gcc, "-Os", "-mlongcalls", "-std=c99", "-Wall", "-Werror", f"-I{MODELS}", "-c", str(unit),
                        "-o", str(obj)], capture_output=True, text=True)
    if r.returncode != 0:
        return {"xtensa": f"compile failed: {r.stderr}"}
    size = str(Path(gcc).with_name("xtensa-esp32-elf-size.exe" if gcc.endswith(".exe") else "xtensa-esp32-elf-size"))
    s = subprocess.run([size, "-A", str(obj)], capture_output=True, text=True).stdout
    sec = {m.group(1): int(m.group(2)) for m in re.finditer(r"^(\.\S+)\s+(\d+)", s, re.M)}
    ver = subprocess.run([gcc, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    keep = {k: v for k, v in sec.items() if k.startswith((".text", ".rodata", ".data", ".bss", ".literal"))}
    return {"xtensa": f"cross-compiled only (-Os -mlongcalls), NOT run: {ver}", "xtensa_sections_bytes": keep}


def write_header_if_stale() -> None:
    if not HEADER_PATH.exists() or HEADER_PATH.read_text(encoding="utf-8") != header_text():
        write_header()


# ============================================================================= C. resources
def _median_time(fn, reps: int) -> float:
    ts = []
    for _ in range(reps):
        t = time.perf_counter(); fn(); ts.append(time.perf_counter() - t)
    return float(np.median(ts))


def resources(c_results: dict = None) -> pd.DataFrame:
    from src import predict as P
    from src import stream_ref as S
    rows = []

    def add(kind, item, value, unit, how):
        rows.append({"kind": kind, "item": item, "value": value, "unit": unit, "how": how})

    # ---------------- MEASURED on this PC
    for f in ("stress_lr_D_w30.joblib", "stress_lr_D_w30.json", "stress_lr_D_w30.h", "feature_spec.json"):
        add("MEASURED", f"file size models/{f}", (MODELS / f).stat().st_size, "bytes", "os.stat")
    bundle, coef, _ = P.load()
    X = pd.read_csv(MODELS / "roundtrip_windows.csv")[S.FEATS].iloc[[0]]
    P.proba_json(coef, X); P.proba_joblib(bundle, X)
    add("MEASURED", "Python inference latency per window, JSON scorer (numpy, 1 row)",
        1e6 * _median_time(lambda: P.proba_json(coef, X), 20000), "us (median of 20000)", "time.perf_counter, this PC")
    add("MEASURED", "Python inference latency per window, joblib pipeline predict_proba (1 row)",
        1e6 * _median_time(lambda: P.proba_joblib(bundle, X), 5000), "us (median of 5000)", "time.perf_counter, this PC")
    cal = pd.read_csv(METRICS / "stream_parity_calibration.csv")
    for dt in ("float64", "float32"):
        g = cal[cal.arithmetic == dt]
        add("MEASURED", f"Python streaming reference CPU time per input sample ({dt}; filters + windows, "
            "BVP+EDA samples counted)", float(g.us_per_sample_pc.median()), "us (median over 15 subjects)",
            "stream_parity_calibration.csv; pure-Python model of the C loop, float32 emulated with numpy scalars")
    if c_results:
        for k in ("float_bench_pc", "double_bench_pc"):
            if k in c_results:
                add("MEASURED", f"C window alert ({k.split('_')[0]}) per call, this PC",
                    float(c_results[k].split()[0]), "ns", "tests/c/model_harness.c bench, MSVC /O2")
        for k, v in c_results.get("xtensa_sections_bytes", {}).items():
            add("MEASURED (compile only)", f"ESP32 object section {k} (score + smoother, -Os)", v, "bytes",
                "xtensa-esp32-elf-size on the cross-compiled header; NOT run on hardware")
    ops = pd.read_csv(METRICS / "stream_op_counts.csv")
    tot = ops.sum(numeric_only=True)
    w = float(tot["windows"])
    per_win = {k: float(tot[k]) / w for k in ("scan", "local_max", "after_distance", "prominence_steps", "sort_n")}
    for k, v in per_win.items():
        add("MEASURED", f"peak detector '{k}' per window (BVP + EDA, all 15 WESAD subjects)", v, "iterations / window",
            "instrumented stream_ref.find_peaks_port (platform-independent count)")
    # ---------------- ESTIMATED for ESP32-WROOM-32E
    B = 4                                                        # float32
    for tag, fb, fe in (("WESAD rates 64 Hz BVP / 4 Hz EDA", 64, 4), ("prototype rates 100 Hz PPG / 10 Hz GSR", 100, 10)):
        nb, ne = 30 * fb, 30 * fe
        parts = {
            "BVP filtered ring (30 s, float32)": nb * B,
            "EDA low-passed + phasic + raw rings (30 s each, float32)": 3 * ne * B,
            "peak scratch: local-max indices (uint16) + keep flags (uint8) + priority order (uint16), worst case N/2 "
            "local maxima": (nb // 2) * (2 + 1 + 2),
            "IBI / beat-time scratch (<= N/distance + 1 floats, x2)": 2 * (nb // int(0.33 * fb) + 1) * B,
            "filter states (3 BVP biquads x2 + 1 EDA biquad x2 + EMA, float32)": (6 + 2 + 1) * B,
            "calibration Welford x2 (n uint32, mean + M2 as double)": 2 * (4 + 8 + 8),
            "stored calibration (sigma_lp_cal, sigma_ph_cal) + smoother byte + counters": 2 * B + 1 + 3 * 4,
            "proposed PPG gate: autocorrelation r(k) over lags 0.33-1.5 s (float32), energies updated per lag": (
                int(1.5 * fb) - int(np.ceil(0.33 * fb)) + 3) * B,
        }
        total = sum(parts.values())
        for k, v in parts.items():
            add("ESTIMATED", f"RAM [{tag}] {k}", v, "bytes", "arithmetic from buffer sizes")
        add("ESTIMATED", f"RAM [{tag}] TOTAL feature front end + model", total, "bytes",
            f"= {total / 1024:.1f} KiB of ~520 KB SRAM ({100 * total / (520 * 1024):.2f} %); excludes RTOS, WiFi/BT "
            "stacks, sensor drivers, logging")
        # operations
        per_sample = 3 * 9 * fb + (9 + 3) * fe                    # biquad = 5 mul + 4 add; EMA 2 mul 1 add
        scale = fb / 64.0
        win_ops = (2 * 2 * nb                                     # two-pass SD
                   + per_win["scan"] * scale + per_win["prominence_steps"] * scale
                   + per_win["sort_n"] * scale * np.log2(max(per_win["sort_n"] * scale, 2))
                   + 2 * ne + 200)                                # slope + model + IBI bookkeeping
        ac = sum(nb - k for k in range(int(np.ceil(0.33 * fb)) - 1, int(1.5 * fb) + 2))
        add("ESTIMATED", f"ops/s [{tag}] per-sample filtering (FLOPs)", per_sample, "ops/s",
            f"3 biquads x 9 FLOP x {fb} Hz + (biquad 9 + EMA 3) x {fe} Hz")
        add("ESTIMATED", f"ops per window [{tag}] features + model (every 5 s)", win_ops, "ops / window",
            "2-pass SD 4N + measured peak-detector iterations (scaled by rate) + sort n log n + slope + model")
        add("ESTIMATED", f"ops per window [{tag}] proposed autocorrelation gate", ac, "MAC / window",
            "sum over lags of (N - k)")
        for cyc in (5, 20):
            load = (per_sample + (win_ops + ac) / 5.0) * cyc / 240e6
            add("ESTIMATED", f"CPU load [{tag}] at an assumed {cyc} cycles per op, 240 MHz, one core", 100 * load,
                "% of one core", f"(per-sample ops/s + window ops / 5 s) x {cyc} / 240e6; cycles per op ASSUMED")
    flash = len(coef["weights_folded"]) + 1 + len(coef["imputer_medians"]) + 2
    dsp = 3 * 5 + 3 * 2 + 5 + 2 + 1
    add("ESTIMATED", "flash: model constants (weights 3, bias, medians 3, thresholds 2) float32", flash * B, "bytes",
        f"{flash} x 4 B")
    add("ESTIMATED", "flash: DSP constants (BVP 3x5 SOS + 3x2 zi, EDA 5 SOS + 2 zi, EMA a) float32", dsp * B, "bytes",
        f"{dsp} x 4 B")
    add("ESTIMATED", "flash: feature + gate + calibration code (not written in C yet)", "2000-8000", "bytes",
        "GUESS by analogy with the measured score+smoother object; ~4 MB flash available")
