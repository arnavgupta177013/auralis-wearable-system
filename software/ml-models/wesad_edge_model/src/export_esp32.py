"""
Export of the deployed stress detection model D for a C implementation, plus resource analysis.  NO firmware.
(WESAD "stress" = lab stressor, not panic/anxiety.)  The saved model in models/ is only READ; nothing is retrained.

    python -m src.export_esp32 --header        models/stress_lr_D_w30.h from models/stress_lr_D_w30.json ONLY
    python -m src.export_esp32 --c-test        compile tests/c/model_harness.c with a host C compiler (if one exists),
                                               run it on the 300 real rows of models/roundtrip_windows.csv (float and
                                               double builds) and compare with Python; cross-compile the header for
                                               the ESP32 (xtensa-esp32-elf-gcc, if installed) and report object size
    python -m src.export_esp32 --resources     MEASURED (this PC) vs ESTIMATED (ESP32) table
                                               -> results/metrics/esp32_resources.csv / .json
    python -m src.export_esp32 --all

The header holds: feature order, window/step, input rates, folded weights, bias, imputer medians, OP1 threshold (as a
probability and as a logit), smoothing m-of-n, calibration duration and the names of the two stored calibration
statistics; plus three tiny inline functions (logit, window alert, m-of-n smoother).  Constants are written with 17
significant digits and cast to AURALIS_REAL (float on the ESP32; double for the host check).
Nothing compiled here has run on an ESP32: the cross-compile gives code size only.
"""

